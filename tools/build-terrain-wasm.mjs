import asc from 'assemblyscript/asc';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
let binary;
const { error, stderr } = await asc.main([
  'engine/wasm/terrain.ts', '--baseDir', root, '--outFile', 'terrain.wasm',
  '--optimizeLevel', '3', '--shrinkLevel', '0', '--runtime', 'stub',
  '--initialMemory', '1', '--maximumMemory', '512', '--noAssert',
], { writeFile: (_path, contents) => { binary = Buffer.from(contents); } });
if (error) throw new Error(stderr.toString());
const module = new WebAssembly.Module(binary);
if (WebAssembly.Module.imports(module).length) throw new Error('Terrain kernels must be import-free');
const outputs = new Map([
  ['server/space/terrain-kernels.wasm', binary],
  ['engine/src/wasm/TerrainKernelBinary.ts', Buffer.from(
    '// Generated by tools/build-terrain-wasm.mjs. Do not edit.\n'
    + `export const TERRAIN_KERNEL_BASE64 = '${binary.toString('base64')}';\n`,
  )],
]);
for (const [path, contents] of outputs) {
  if (process.argv.includes('--check')) {
    if (!contents.equals(await readFile(root + path))) throw new Error(`Stale WASM output: ${path}`);
  } else await writeFile(root + path, contents);
}
console.log(`Terrain WASM: ${binary.length} bytes${process.argv.includes('--check') ? ' (verified)' : ''}`);
