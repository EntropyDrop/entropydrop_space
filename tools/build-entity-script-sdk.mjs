import { readFileSync, writeFileSync } from 'node:fs';
const input = new URL('../engine/assembly/entity-sdk.ts', import.meta.url);
const output = new URL('../engine/src/scripting/EntityScriptSDK.generated.ts', import.meta.url);
const text = '// Generated by tools/build-entity-script-sdk.mjs. DO NOT EDIT.\nexport const ENTITY_SCRIPT_SDK = ' + JSON.stringify(readFileSync(input, 'utf8')) + ';\n';
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== text) throw new Error('Entity SDK is stale; run npm run generate:script-sdk');
} else writeFileSync(output, text);
