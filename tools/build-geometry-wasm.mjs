import asc from 'assemblyscript/asc';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
let binary;
const { error, stderr } = await asc.main([
  'engine/wasm/geometry.ts', '--baseDir', root, '--outFile', 'geometry.wasm',
  '--optimizeLevel', '3', '--shrinkLevel', '0', '--runtime', 'stub',
  '--initialMemory', '1', '--maximumMemory', '2048', '--noAssert',
], { writeFile: (_path, contents) => { binary = Buffer.from(contents); } });
if (error) throw new Error(stderr.toString());
const module = new WebAssembly.Module(binary);
const imports = WebAssembly.Module.imports(module);
if (imports.some(i => i.module !== 'math' || i.kind !== 'function' || !['sin', 'cos', 'atan2'].includes(i.name))) {
  throw new Error('Geometry kernels may import only scalar Math sin/cos/atan2');
}
const path = root + 'engine/src/wasm/GeometryKernelBinary.ts';
const contents = Buffer.from('// Generated by tools/build-geometry-wasm.mjs. Do not edit.\n'
  + `export const GEOMETRY_KERNEL_BASE64 = '${binary.toString('base64')}';\n`);
if (process.argv.includes('--check')) {
  if (!contents.equals(await readFile(path))) throw new Error('Stale geometry WASM output');
} else await writeFile(path, contents);
console.log(`Geometry WASM: ${binary.length} bytes${process.argv.includes('--check') ? ' (verified)' : ''}`);
